/**
 * Shows a map of Vienna with the districts filled in with colors according to the given values.
 * @param values One numerical value per Vienna district (23 values).
 */
export function visualize_district_info(values) {
    if (!values || values.length !== DISTRICT_COUNT) {
        throw new Error(`visualize_district_info() expects exactly ${DISTRICT_COUNT} values`);
    }

    districts ??= createOverlay();
    update(districts, values);
}

/**
 * Creates an overlays as an svg element and appends it to the document body.
 */
function createOverlay() {
    const svg_template = new DOMParser().parseFromString(SVG, "image/svg+xml").documentElement;
    const svg = globalThis.document.importNode(svg_template, true);
    svg.style.cssText =
        "position:fixed;inset:0;width:100%;height:100%;pointer-events:none;z-index:0";
    document.body.append(svg);

    const result = collectDistricts(svg);

    return result;
}

